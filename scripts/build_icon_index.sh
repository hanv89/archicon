Generated by `scripts/build_icon_index.sh`. Do not edit by hand — edit
`scripts/fixtures/icon-index-tags-fabric.tsv` and regenerate.

Each row points at a usable PNG path. Microsoft Fabric ships icons in
multiple sizes (24/28/32/40/48) and suffix families: `_item` (per-artifact),
`_non-item` (workspace + action verbs), `_color` (workload brand), plain
(no suffix).

Find an icon by name or tag:

```bash
grep -i 'lakehouse' dist/Fabric/INDEX.md
grep -F '`pipeline`' dist/Fabric/INDEX.md
```

EOF
    echo "| path | name | size | suffix | description | tags |"
    echo "|------|------|------|--------|-------------|------|"

    find "${dist_root}/png" -name '*.png' -type f | sort | while IFS= read -r png; do
      local rel fname stem size suffix
      rel="${png#${REPO_ROOT}/}"
      fname="$(basename "${png}" .png)"
      if [[ "${fname}" =~ ^(.+)_([0-9]+)_([^_]+)$ ]]; then
        stem="${BASH_REMATCH[1]}"
