#!/usr/bin/env bash
# Build per-vendor INDEX.md catalog files under dist/<Vendor>/.
#
# Each INDEX.md is a markdown table with one row per usable PNG path.
# Description + tags come from a per-vendor lookup TSV at
# scripts/fixtures/icon-index-tags-<vendor>.tsv (filename stem → row,
# category/suffix prefix fallback, heuristic last). Edit the TSV, then
# re-run this script; the INDEX is regenerated deterministically.
#
# Usage:
#   bash scripts/build_icon_index.sh           # both vendors
#   bash scripts/build_icon_index.sh azure
#   bash scripts/build_icon_index.sh fabric

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
# shellcheck source=scripts/_lib_icon_build.sh
. "${SCRIPT_DIR}/_lib_icon_build.sh"
set_locale_deterministic

FIXTURES_DIR="${SCRIPT_DIR}/fixtures"
AZURE_TSV="${FIXTURES_DIR}/icon-index-tags-azure.tsv"
FABRIC_TSV="${FIXTURES_DIR}/icon-index-tags-fabric.tsv"
KUBERNETES_TSV="${FIXTURES_DIR}/icon-index-tags-kubernetes.tsv"
FLUENTUI_TSV="${FIXTURES_DIR}/icon-index-tags-fluentui.tsv"
DEVICON_TSV="${FIXTURES_DIR}/icon-index-tags-devicon.tsv"
# >>> AWS-INDEX-BEGIN (Phase 3 net-new vendor; per-stem tags TSV is optional —
#     when absent the AWS index uses heuristic name/description/tags only).
AWS_TSV="${FIXTURES_DIR}/icon-index-tags-aws.tsv"
# <<< AWS-INDEX-END

# lookup <tsv_file> <key>
#   Prints "<name><TAB><description><TAB><tags>" if a row exists for the
#   key, or empty if not. The TSV columns are key\tname\tdescription\ttags.
#   A literal "-" in name or description means "fall back to heuristic"
#   (lets a row override only the tags column).
lookup() {
  local tsv="$1"
  local key="$2"
  [ -f "${tsv}" ] || return 0
  awk -F'\t' -v k="${key}" '$1 == k { print $2 "\t" $3 "\t" $4; exit }' "${tsv}"
}

# lookup_devicon <tsv_file> <key>
#   Like lookup() but Devicon TSVs have 5 columns: key\tname\tcategory\tdescription\ttags.
#   Prints "<name><TAB><category><TAB><description><TAB><tags>" if a row exists, or empty.
#   A literal "-" in any column means "fall back to heuristic".
lookup_devicon() {
  local tsv="$1"
  local key="$2"
  [ -f "${tsv}" ] || return 0
  awk -F'\t' -v k="${key}" '$1 == k { print $2 "\t" $3 "\t" $4 "\t" $5; exit }' "${tsv}"
}

ACRONYMS_AZURE_TSV="${FIXTURES_DIR}/acronyms-azure.tsv"
# >>> AWS-INDEX-BEGIN
ACRONYMS_AWS_TSV="${FIXTURES_DIR}/acronyms-aws.tsv"
# <<< AWS-INDEX-END

# apply_acronyms <tsv> — read stdin, apply each `<pattern><TAB><replacement>` row
# from the TSV in order as `sed -E 's/\b<pattern>\b/<replacement>/g'`. Order in
# the file matters (single-token acronym fixes precede multi-token re-joins).
# Extracted from azure_humanize so AWS/GCP (Phase 3) can supply their own TSV.
apply_acronyms() {
  local tsv="$1" expr="" pat rep
  while IFS=$'\t' read -r pat rep; do
    case "${pat}" in ''|\#*) continue ;; esac
    [ -n "${rep}" ] || continue
    expr="${expr}s/\\b${pat}\\b/${rep}/g;"
  done < "${tsv}"
  if [ -n "${expr}" ]; then sed -E "${expr}"; else cat; fi
}

# azure_humanize <PascalCaseStem>
#   AzureVirtualMachine → "Azure Virtual Machine"; AzureSQLServer → "Azure SQL Server".
#   PascalCase split, then the acronym whitelist in scripts/fixtures/acronyms-azure.tsv
#   uppercases/re-joins known mixed-case acronyms (e.g. "Cosmos Db" → "Cosmos DB").
#   Edit the TSV (not this function) to extend the list.
azure_humanize() {
  printf '%s\n' "$1" \
    | sed -E 's/([a-z])([A-Z])/\1 \2/g; s/([A-Z])([A-Z][a-z])/\1 \2/g' \
    | apply_acronyms "${ACRONYMS_AZURE_TSV}"
}

# fabric_humanize <snake_case_stem>
#   lakehouse → "Lakehouse"; power_bi → "Power Bi" (override via TSV to "Power BI").
fabric_humanize() {
  printf '%s\n' "$1" | tr '_' ' ' | awk '{ for(i=1;i<=NF;i++) $i = toupper(substr($i,1,1)) substr($i,2); print }'
}

# >>> AWS-INDEX-BEGIN
# aws_humanize <PascalCaseStem>
#   EC2 → "EC2"; CloudFront → "CloudFront"; SimpleStorageService → "Simple
#   Storage Service"; IoTCore → "IoT Core". Same PascalCase splitter as Azure
#   (all-caps acronyms left intact) followed by the AWS acronym whitelist in
#   scripts/fixtures/acronyms-aws.tsv (fixes "Io T" → "IoT" and re-joins
#   one-word brands like "Cloud Front" → "CloudFront"). NO vendor prefix —
#   AWS filenames already carry the service name. Edit the TSV (not this
#   function) to extend the list.
aws_humanize() {
  printf '%s\n' "$1" \
    | sed -E 's/([a-z])([A-Z])/\1 \2/g; s/([A-Z])([A-Z][a-z])/\1 \2/g' \
    | apply_acronyms "${ACRONYMS_AWS_TSV}"
}
# <<< AWS-INDEX-END

build_azure_index() {
  local dist_root="${REPO_ROOT}/dist/Azure"
  local out="${dist_root}/INDEX.md"

  {
    cat <<'EOF'
# Azure icon index

Generated by `scripts/build_icon_index.sh`. Do not edit by hand — edit
`scripts/fixtures/icon-index-tags-azure.tsv` and regenerate.

Each row points at a usable PNG path. Colored and monochrome `(m)` variants
ship as separate rows so the agent can copy the exact URL needed.

Find an icon by name, category, or tag:

```bash
grep -i 'kubernetes' dist/Azure/INDEX.md      # by name
grep -F '`compute`' dist/Azure/INDEX.md       # by tag
```

EOF
    echo "| path | name | category | variant | description | tags |"
    echo "|------|------|----------|---------|-------------|------|"

    find "${dist_root}" -mindepth 2 -name '*.png' -type f | sort | while IFS= read -r png; do
      local rel category fname stem variant
      rel="${png#${REPO_ROOT}/}"
      category="$(basename "$(dirname "${png}")")"
      fname="$(basename "${png}" .png)"
      if [[ "${fname}" == *'(m)' ]]; then
        stem="${fname%(m)}"
        variant="monochrome"
      else
        stem="${fname}"
        variant="colored"
      fi

      # Lookup precedence (each column independently, "-" means heuristic):
      #   1. Per-stem row (any of name/description/tags can override).
      #   2. tags fall back to cat:<Category> row's tags if no per-stem tags.
      #   3. Final fallback: heuristic name + description, lowercase-category tags.
      local row name description tags cat_row n d t
      name=""
      description=""
      tags=""
      row="$(lookup "${AZURE_TSV}" "${stem}")"
      if [ -n "${row}" ]; then
        IFS=$'\t' read -r n d t <<< "${row}"
        [ -n "${n}" ] && [ "${n}" != "-" ] && name="${n}"
        [ -n "${d}" ] && [ "${d}" != "-" ] && description="${d}"
        [ -n "${t}" ] && [ "${t}" != "-" ] && tags="${t}"
      fi
      if [ -z "${tags}" ]; then
        cat_row="$(lookup "${AZURE_TSV}" "cat:${category}")"
        if [ -n "${cat_row}" ]; then
          IFS=$'\t' read -r _ _ t <<< "${cat_row}"
          [ -n "${t}" ] && [ "${t}" != "-" ] && tags="${t}"
        fi
      fi
      [ -z "${name}" ] && name="$(azure_humanize "${stem}")"
      [ -z "${description}" ] && description="Microsoft Azure $(azure_humanize "${stem}" | sed -E 's/^Azure ?//')"
      [ -z "${tags}" ] && tags="\`$(echo "${category}" | tr '[:upper:]' '[:lower:]')\`"

      printf '| `%s` | %s | %s | %s | %s | %s |\n' \
        "${rel}" "${name}" "${category}" "${variant}" "${description}" "${tags}"
    done
  } > "${out}"

  local count
  count=$(find "${dist_root}" -mindepth 2 -name '*.png' -type f | wc -l)
  echo "Azure: ${count} rows → ${out#${REPO_ROOT}/}"
}

build_fabric_index() {
