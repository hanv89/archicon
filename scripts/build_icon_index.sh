      name=""
      description=""
      tags=""
      row="$(lookup "${FABRIC_TSV}" "${stem}")"
      if [ -n "${row}" ]; then
        IFS=$'\t' read -r n d t <<< "${row}"
        [ -n "${n}" ] && [ "${n}" != "-" ] && name="${n}"
        [ -n "${d}" ] && [ "${d}" != "-" ] && description="${d}"
        [ -n "${t}" ] && [ "${t}" != "-" ] && tags="${t}"
      fi
      if [ -z "${tags}" ]; then
        suffix_row="$(lookup "${FABRIC_TSV}" "suffix:${suffix}")"
        if [ -n "${suffix_row}" ]; then
          IFS=$'\t' read -r _ _ t <<< "${suffix_row}"
          [ -n "${t}" ] && [ "${t}" != "-" ] && tags="${t}"
        fi
      fi
      [ -z "${name}" ] && name="$(fabric_humanize "${stem}")"
      [ -z "${description}" ] && description="Microsoft Fabric $(fabric_humanize "${stem}")"
      [ -z "${tags}" ] && tags="\`fabric\`, \`${suffix}\`"

      printf '| `%s` | %s | %s | %s | %s | %s |\n' \
        "${rel}" "${name}" "${size}" "${suffix}" "${description}" "${tags}"
    done
  } > "${out}"

  local count
  count=$(find "${dist_root}/png" -name '*.png' -type f | wc -l)
  echo "Fabric: ${count} rows → ${out#${REPO_ROOT}/}"
}

build_kubernetes_index() {
  local dist_root="${REPO_ROOT}/dist/Kubernetes"
  local out="${dist_root}/INDEX.md"

  {
    cat <<'EOF'
# Kubernetes icon index

Generated by `scripts/build_icon_index.sh`. Do not edit by hand — edit
`scripts/fixtures/icon-index-tags-kubernetes.tsv` and regenerate.

Each row points at a usable PNG path. The Kubernetes icon set ships
two stylistic variants (labeled vs unlabeled) across resources,
control-plane components, and infrastructure components — at 128px
and 256px sizes.

Find an icon by name, variant, or tag:

```bash
grep -i 'pod' dist/Kubernetes/INDEX.md          # by name
grep -F '`network`' dist/Kubernetes/INDEX.md    # by tag
grep -F '| labeled |' dist/Kubernetes/INDEX.md  # by variant
```

EOF
    echo "| path | name | variant | size | description | tags |"
    echo "|------|------|---------|------|-------------|------|"

    find "${dist_root}/png" -name '*.png' -type f | sort | while IFS= read -r png; do
      local rel fname stem size variant subdir
      rel="${png#${REPO_ROOT}/}"
      fname="$(basename "${png}" .png)"
      # Derive subdir family. Path looks like dist/Kubernetes/png/<family>/<labeled|unlabeled>/<file>.png
      subdir="$(dirname "${rel#dist/Kubernetes/png/}")"
      case "${subdir}" in
        resources/labeled)                 variant="labeled" ;;
        resources/unlabeled)               variant="unlabeled" ;;
        control_plane_components/labeled)  variant="control-plane-labeled" ;;
        control_plane_components/unlabeled) variant="control-plane-unlabeled" ;;
        infrastructure_components/labeled) variant="infra-labeled" ;;
        infrastructure_components/unlabeled) variant="infra-unlabeled" ;;
        *)                                 variant="${subdir}" ;;
      esac
      # Stem + size: filename is `<stem>-<size>.png` where stem may contain dashes.
      if [[ "${fname}" =~ ^(.+)-([0-9]+)$ ]]; then
        stem="${BASH_REMATCH[1]}"
        size="${BASH_REMATCH[2]}"
      else
        echo "WARN: unrecognized Kubernetes filename: ${fname}" >&2
        continue
      fi

      # Lookup precedence (each column independently, "-" means heuristic):
      #   1. Per-stem row (any of name/description/tags can override).
      #   2. Final fallback: heuristic name (stem as-is, uppercased first char),
      #      description ("Kubernetes <stem>"), tags ("`kubernetes`, `<variant>`").
