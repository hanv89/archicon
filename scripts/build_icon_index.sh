        [ -n "${n}" ] && [ "${n}" != "-" ] && name="${n}"
        [ -n "${d}" ] && [ "${d}" != "-" ] && description="${d}"
        [ -n "${t}" ] && [ "${t}" != "-" ] && tags="${t}"
      fi
      [ -z "${name}" ] && name="$(printf '%s' "${stem}" | awk '{print toupper(substr($0,1,1)) substr($0,2)}')"
      [ -z "${description}" ] && description="Kubernetes ${name}"
      [ -z "${tags}" ] && tags="\`kubernetes\`, \`${variant}\`"

      printf '| `%s` | %s | %s | %s | %s | %s |\n' \
        "${rel}" "${name}" "${variant}" "${size}" "${description}" "${tags}"
    done
  } > "${out}"

  local count
  count=$(find "${dist_root}/png" -name '*.png' -type f | wc -l)
  echo "Kubernetes: ${count} rows → ${out#${REPO_ROOT}/}"
